  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept());
  await mkdir(evidence, { recursive: true });
  await page.goto('/');
  const one = page.locator('#level-one'), two = page.locator('#level-two');
